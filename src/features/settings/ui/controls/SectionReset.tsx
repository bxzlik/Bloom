import { Ico } from '@shared/ui/icons/solar'
import { useT } from '@shared/i18n'

/**
 * Кнопка «сбросить раздел» — иконка в правом верхнем углу содержимого секции.
 *
 * Живёт отдельным элементом, а не в шапке раздела (`.s-section-head`): шапка
 * скрыта, роль заголовка забрал ряд вкладок в шапке панели, и кнопка вместе с
 * ней была невидима. Позиционируется абсолютно (см. `.s-sec-reset`), поэтому
 * встаёт на одну строку с первой подписью группы и ничего не сдвигает.
 *
 * Подписи нет намеренно: рядом идут подписи групп, и текст «Сбросить» их
 * перевешивал бы. Смысл несёт `aria-label` — нативные тултипы в приложении
 * запрещены, всплывающей подсказки здесь не будет.
 *
 * Сброс у каждого раздела свой: разделы делят общие сторы, поэтому «сбросить
 * всё» снесло бы чужие настройки. Что именно сбрасывать — решает раздел.
 */
const ResetBtn = ({ cls, onReset, disabled }: { cls: string; onReset: () => void; disabled?: boolean }) => {
  const t = useT()
  return (
    <button className={cls} aria-label={t('common.reset')} onClick={onReset} disabled={disabled}>
      <Ico name="refresh" width={14} height={14} />
    </button>
  )
}

/** Сброс всего раздела — угол содержимого секции. */
export const SectionReset = ({ onReset }: { onReset: () => void }) => (
  <ResetBtn cls="s-sec-reset" onReset={onReset} />
)

/**
 * Сброс ОДНОЙ группы настроек — правый верхний угол карточки, на линии её
 * заголовка. Карточка знает только свои ключи, поэтому сброс точечный: сосед
 * по разделу от него не страдает.
 *
 * Кладётся первым ребёнком `.sc` — позиционируется абсолютно, поэтому порядок
 * в разметке ни на что не влияет и заголовок сдвигать не нужно.
 */
export const CardReset = ({ onReset }: { onReset: () => void }) => (
  <ResetBtn cls="sc-reset" onReset={onReset} />
)

/**
 * Сброс ОДНОЙ строки-настройки — вплотную к её названию.
 *
 * Нужен там, где карточка это одна строка «подпись + тумблер»: угол карточки
 * там занят самим тумблером, и кнопка в углу спорила бы с ним за место и за
 * взгляд. Кладётся ВНУТРЬ `.sl2`, поэтому едет вместе с названием.
 */
export const RowReset = ({ onReset }: { onReset: () => void }) => (
  <ResetBtn cls="sl-reset" onReset={onReset} />
)

/**
 * Сброс группы — в её строке-заголовке (`.s-cat-label`).
 *
 * Нужен там, где карточка занята своим содержимым с самого верха и угол ей не
 * отдать: выбор темы начинается рядом кнопок «пресет + создать», и кнопка в
 * углу села бы прямо на «+». Заголовок группы стоит НАД карточкой и свободен.
 */
export const CatReset = ({ onReset, disabled }: { onReset: () => void; disabled?: boolean }) => (
  <ResetBtn cls="cat-reset" onReset={onReset} disabled={disabled} />
)
